#!/usr/bin/env python
"""Generate docs/api/response-inventory.md from the LIVE OpenAPI document and the pre-change runtime baseline (V41-17.03, Batch 3).

    python scripts/api_response_inventory.py

For every operation: success status, media type, declared response schema, top-level field counts (required, optional, nullable), whether it is a paginated envelope,
the classification (A stable JSON; B multiple success statuses; C bodyless; D streaming/file; E dynamic or insufficiently characterised) and the frontend files that call it.
Nothing is hand-entered: the table is derived from the application's own OpenAPI and from `frontend/src` text search."""
import dataclasses
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app.core.config import get_settings  # noqa: E402
from app.main import create_app  # noqa: E402

OUT = ROOT / "docs" / "api" / "response-inventory.md"
BASELINE = ROOT / "evaluation" / "api-quality" / "response-baseline-pre-batch3.json"
DYNAMIC = {"GET /api/v1/evaluation/reports": "built from evidence files on disk", "GET /api/v1/observability/summary": "process counters and timers are dynamic series",
           "GET /api/v1/metrics": "count maps keyed by data values (typed as maps of integers)", "GET /api/v1/tenant-profile": "tenant-defined profile (typed by TenantProfile)"}


def resolve(schema, spec):
    while "$ref" in schema:
        schema = spec["components"]["schemas"][schema["$ref"].rsplit("/", 1)[-1]]
    return schema


def describe(schema, spec):
    schema = resolve(schema, spec)
    alts = schema.get("anyOf") or schema.get("oneOf")
    if alts:
        return [d for a in alts for d in describe(a, spec)]
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    nullable = {k for k, v in props.items() if any(x.get("type") == "null" for x in v.get("anyOf", []))}
    return [{"props": len(props), "required": len(required), "optional": len(props) - len(required), "nullable": len(nullable), "paginated": {"total", "limit", "offset", "items"} <= set(props)}]


def frontend_files(path):
    pattern = re.escape(re.sub(r"^/api/v1", "", path)).replace(r"\{", "{").replace(r"\}", "}")
    pattern = re.sub(r"\{[^}]+\}", r"[^\"'`/?]+|\\$\\{[^}]+\\}", pattern)
    files = set()
    for f in (ROOT / "frontend" / "src").rglob("*.ts*"):
        text = f.read_text(encoding="utf-8", errors="ignore")
        if re.search(r"[\"'`](?:/api/v1)?" + pattern + r"(?:[\"'`?/]|$)", text) and ".test." not in f.name:
            files.add(f.relative_to(ROOT / "frontend" / "src").as_posix())
    return sorted(files)


def main():
    settings = dataclasses.replace(get_settings(db_name="eaop_test"), jwt_secret="inventory-secret-not-for-production-0123456789", llm_backend="deterministic", embedding_backend="deterministic")
    spec = create_app(settings).openapi()
    baseline = json.loads(BASELINE.read_text(encoding="utf-8")) if BASELINE.exists() else {}
    rows = []
    for path, ops in sorted(spec["paths"].items()):
        for method, op in sorted(ops.items()):
            if method not in ("get", "post", "put", "patch", "delete"):
                continue
            key = f"{method.upper()} {path}"
            ok = {c: r for c, r in op["responses"].items() if c.startswith("2")}
            code = sorted(ok)[0]
            media = next(iter(ok[code].get("content", {"(none)": {}})))
            schema = ok[code].get("content", {}).get(media, {}).get("schema", {})
            names = " or ".join(sorted(s["$ref"].rsplit("/", 1)[-1] for s in schema.get("anyOf", [schema]) if "$ref" in s)) or "inline"
            d = describe(schema, spec) if schema else [{"props": 0, "required": 0, "optional": 0, "nullable": 0, "paginated": False}]
            cls = "C" if media == "(none)" else "D" if not media.startswith("application/json") else "B" if len(ok) > 1 else "E" if key in DYNAMIC else "A"
            base = baseline.get(key, {})
            rows.append((key, code, media, names, "/".join(str(x["props"]) for x in d), "/".join(str(x["required"]) for x in d), "/".join(str(x["nullable"]) for x in d),
                         "yes" if any(x["paginated"] for x in d) else "no", cls, "yes" if base else "no", ", ".join(frontend_files(path)) or "none found"))
    lines = ["# API response inventory (generated)", "",
             "Generated by `python scripts/api_response_inventory.py` from the live OpenAPI document, the pre-Batch-3 runtime baseline (`evaluation/api-quality/response-baseline-pre-batch3.json`) and a text search of `frontend/src`. "
             "Classes: A stable JSON; B multiple success statuses; C bodyless; D streaming or file; E dynamic or insufficiently characterised (typed, but its content is derived from external data). "
             "Union responses list `props/required/nullable` once per alternative.", "",
             f"Operations: {len(rows)}. Class counts: " + ", ".join(f"{c}={sum(1 for r in rows if r[8] == c)}" for c in "ABCDE"), "",
             "| Operation | Success | Media type | Response schema | Fields | Required | Nullable | Paginated | Class | In baseline | Frontend consumers |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    lines += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    lines += ["", "The frontend column is a literal text search of `frontend/src`; \"none found\" means no matching path literal (a call may be built dynamically). Frontend compatibility is established by the unchanged runtime shapes and by the frontend type-check and tests, not by this column.", ""]
    codes = {}
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            if method in ("get", "post", "put", "patch", "delete"):
                for c in op["responses"]:
                    codes.setdefault(c, []).append(f"{method.upper()} {path}")
    lines += ["", "## HTTP statuses (from the live OpenAPI document)", "", "Success: " + ", ".join(f"{len(v)} operations return {c}" for c, v in sorted(codes.items()) if c.startswith("2")) + ". The 201 operations: "
              + "; ".join(sorted(codes.get("201", []))) + ".", "",
              "Errors documented with the standardized envelope (`ErrorResponse`; 413 from the size-limit middleware uses `SizeLimitErrorResponse`): "
              + ", ".join(f"{c}: {len(v)} operations" for c, v in sorted(codes.items()) if not c.startswith("2")) + ". The per-operation table is `ERROR_STATUSES` in `backend/app/api/v1/error_contracts.py`.", ""]
    lines += ["", "Class E operations are typed and validated against runtime responses; the class records that their content depends on external data (evidence files, metric series, tenant-defined profiles), so their fields may be null or empty at runtime.", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(rows)} operations)")


if __name__ == "__main__":
    main()
