#!/usr/bin/env python
"""Write the full requirements-to-solution traceability matrix for ALL 238 original V4.1 requirements (specification Part 6).

    python scripts/generate_full_traceability.py            # writes docs/traceability/v4.1-full-traceability-matrix.md and .json
    python scripts/generate_full_traceability.py --check    # exit 1 if the committed files are out of date

Each requirement is mapped to the six items Part 6 asks for: customer need, technical implementation, component or API, test case, acceptance criterion, evidence artifact.
Sources (nothing is typed by hand here except the customer-need sentence per specification part, shared with scripts/generate_solution_matrix.py):
  * docs/specification/v4.1-requirements.json: id, original wording reference, acceptance criterion, status, and the implementation, tests and evidence recorded on the requirement;
  * scripts/traceability_data.py: for roll-up requirements (definition-of-done items, final deliverables) that cite catalogue ids, the catalogue entries' implementation, tests and evidence
    are INHERITED and marked "via R<id>".
A cell that has nothing recorded says "none recorded"; such requirements are counted and listed, never padded. Customer needs are fictional assumptions; statuses are the implementing
engineer's assessment, not independent validation."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import traceability_data as catalogue  # noqa: E402
from generate_solution_matrix import NEEDS  # noqa: E402

OUT_MD = ROOT / "docs" / "traceability" / "v4.1-full-traceability-matrix.md"
OUT_JSON = ROOT / "docs" / "traceability" / "v4.1-full-traceability-matrix.json"
STATUS = {"V": "verified", "P": "partial", "M": "missing", "N": "not evaluable"}
MORE_NEEDS = {
    1: "The owner needs one coherent, working platform that demonstrates the whole forward-deployed engineering lifecycle for two customers.",
    4: "Both customers need the core workflow, security and reliability to work before optional technology is added.",
    28: "Engineers need a predictable repository layout so they can find code, tests, evidence and documents.",
    31: "The owner needs the work delivered in verifiable phases, each closed with tests and a review.",
    34: "The owner needs a complete, honest set of deliverables and a record of how they were verified.",
}
API_HINT = re.compile(r"backend/app/api/|frontend/src/|mock-services/|scripts/|workers/|infrastructure/|\.github/")


def build() -> list[dict]:
    reqs = json.loads((ROOT / "docs" / "specification" / "v4.1-requirements.json").read_text(encoding="utf-8"))
    reqs = reqs["requirements"] if isinstance(reqs, dict) else reqs
    by_cat = {r["id"]: r for r in catalogue.REQUIREMENTS}
    rows = []
    for r in reqs:
        impl, tests, evidence, via = list(r["impl"]), list(r["tests"]), list(r["evidence"]), []
        for cid in r.get("cat", []):
            c = by_cat.get(cid)
            if not c:
                continue
            for target, source in ((impl, c["implementation"]), (tests, c["tests"]), (evidence, c["evidence"])):
                added = [x for x in source if x not in target]
                if added:
                    target.extend(added)
                    if cid not in via:
                        via.append(cid)
        components = [p for p in impl if API_HINT.search(p)] or impl
        need = {**NEEDS, **MORE_NEEDS}.get(r["part"])
        rows.append({"id": r["id"], "part": r["part"], "spec_lines": r["line_ref"], "requirement": r["title"], "kind": r["kind"], "status": STATUS[r["status"]],
                     "customer_need": need, "implementation": impl, "components_or_apis": components, "tests": tests, "acceptance_criterion": r["accept"], "evidence": evidence,
                     "inherited_from_catalogue": via, "limitation": r["gap"],
                     "complete": bool(need and impl and tests and r["accept"] and evidence)})
    return rows


def cell(items, limit=6) -> str:
    if not items:
        return "none recorded"
    shown = "<br>".join(f"`{i}`" for i in items[:limit])
    return shown + (f"<br>(+{len(items) - limit} more in the JSON)" if len(items) > limit else "")


def render(rows: list[dict]) -> str:
    complete = sum(r["complete"] for r in rows)
    counts = {s: sum(r["status"] == s for r in rows) for s in STATUS.values()}
    incomplete_verified = [r["id"] for r in rows if r["status"] == "verified" and not r["complete"]]
    lines = ["# Full requirements-to-solution traceability matrix (all 238 original V4.1 requirements)", "",
             "Generated by `python scripts/generate_full_traceability.py` (do not edit by hand); checked by `tests/test_full_traceability.py`. It maps every original requirement to the six "
             "items of specification Part 6. Customer needs are **fictional assumptions** ([customer discovery](../customer-discovery/README.md)). Status is the implementing engineer's "
             "assessment from `docs/specification/v4.1-requirements.json`, not independent validation. \"via R…\" means the implementation, tests or evidence are inherited from the catalogue "
             "entries the requirement cites. \"none recorded\" means exactly that.", "",
             f"Requirements: {len(rows)}. Status: " + ", ".join(f"{k} {v}" for k, v in counts.items()) + f". All six items present: **{complete} of {len(rows)}**. "
             f"Verified requirements without all six items: {len(incomplete_verified)}" + (f" ({', '.join(incomplete_verified)})" if incomplete_verified else "") + ".", ""]
    for part in sorted({r["part"] for r in rows}):
        part_rows = [r for r in rows if r["part"] == part]
        lines += [f"## Specification part {part}", "", f"**Customer need.** {part_rows[0]['customer_need'] or 'none recorded'}", "",
                  "| Id (lines) | Requirement | Technical implementation | Component or API | Test cases | Acceptance criterion | Evidence | Status |", "|---|---|---|---|---|---|---|---|"]
        for r in part_rows:
            via = f" (via {', '.join(r['inherited_from_catalogue'])})" if r["inherited_from_catalogue"] else ""
            status = f"**{r['status']}**" + (f": {r['limitation']}" if r["limitation"] and r["status"] != "verified" else "")
            lines.append(f"| {r['id']} ({r['spec_lines']}) | {r['requirement']} | {cell(r['implementation'])}{via} | {cell(r['components_or_apis'], 3)} | {cell(r['tests'])} | "
                         f"{r['acceptance_criterion']} | {cell(r['evidence'], 4)} | {status.replace('|', '/')} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    rows = build()
    md, js = render(rows), json.dumps({"generated_by": "scripts/generate_full_traceability.py", "requirements": rows}, indent=1) + "\n"
    if "--check" in sys.argv:
        ok = OUT_MD.exists() and OUT_MD.read_text(encoding="utf-8") == md and OUT_JSON.read_text(encoding="utf-8") == js
        print("up to date" if ok else "OUT OF DATE")
        return 0 if ok else 1
    OUT_MD.write_text(md, encoding="utf-8", newline="\n")
    OUT_JSON.write_text(js, encoding="utf-8", newline="\n")
    incomplete = [(r["id"], r["status"]) for r in rows if not r["complete"]]
    print(f"{len(rows)} requirements; all six items: {len(rows) - len(incomplete)}; incomplete: {len(incomplete)}")
    print("incomplete verified:", [i for i, s in incomplete if s == "verified"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
