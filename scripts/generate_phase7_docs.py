"""Render the outcome tables in docs/reliability and docs/customer-acceptance from the recorded JSON reports.

    python scripts/generate_phase7_docs.py

The tables are generated so the documents cannot drift from (or invent) results. Narrative sections are static text.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FI_SPEC = {"FI-01": "HTTP 503 outage", "FI-02": "HTTP 429 rate limiting", "FI-03": "Network timeout", "FI-04": "Malformed API response",
           "FI-05": "Unauthorized cross-tenant access", "FI-06": "Concurrent approvals", "FI-07": "Worker interruption",
           "FI-08": "Prompt injection via documents", "FI-09": "Duplicate ingestion", "FI-10": "Database interruption"}


def fi_doc() -> str:
    d = json.loads((ROOT / "evaluation/failure-reports/phase7/fi-report.json").read_text(encoding="utf-8"))
    rows = ["| ID | Scenario | Fault injected | Actual behaviour | Recovery | Duplicate external actions | Data integrity | Result |", "|---|---|---|---|---|---|---|---|"]
    for s in d["scenarios"]:
        cell = lambda t: str(t).replace("|", "/").replace("\n", " ")[:260]  # noqa: E731
        rows.append(f"| {s['id']} | {cell(s['name'])} | {cell(s['injected_fault'])} | {cell(s['actual_behavior'])} | {cell(s['recovery_action'])} | "
                    f"{s['duplicate_external_actions']} | {cell(s['data_integrity'])[:120]} | {'PASS' if s['passed'] else 'FAIL'} |")
    return "\n".join(rows)


def uat_doc(mode: str) -> str:
    d = json.loads((ROOT / f"evaluation/customer-acceptance/{mode}/uat-report.json").read_text(encoding="utf-8"))
    rows = ["| ID | Customer | Scenario | Requirements | Actual | Result |", "|---|---|---|---|---|---|"]
    for s in d["scenarios"]:
        actual = str(s["actual"]).replace("|", "/").replace("\n", " ")[:220]
        rows.append(f"| {s['id']} | {s['customer'].split(' (')[0]} | {s['title']} | {', '.join(s['requirement_ids'])} | {actual} | {s['status'].upper()} |")
    return f"{d['summary']['passed']} of {d['summary']['scenarios']} passed ({d['ai_evidence']}).\n\n" + "\n".join(rows)


