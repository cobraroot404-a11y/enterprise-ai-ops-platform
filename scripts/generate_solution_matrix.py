"""Write docs/customer-delivery/02-requirements-to-solution-matrix.md from the traceability catalogue.

    python scripts/generate_solution_matrix.py

Every catalogue requirement is mapped to the six items Part 6 of the specification asks for: customer need, technical implementation, component or API, test case, acceptance criterion and
evidence artifact. The only hand-written input is the customer-need statement per specification part (below); everything else is read from scripts/traceability_data.py, so the matrix can
not drift from the catalogue. Customer needs are FICTIONAL assumptions (docs/customer-discovery); statuses are the catalogue statuses, not independent validation."""
