def cell(items) -> str:
    return "<br>".join(f"`{i}`" for i in items) if items else "none"


def main() -> None:
    by_part = defaultdict(list)
    for r in t.REQUIREMENTS:
        by_part[r["part"]].append(r)
    lines = ["# Requirements-to-solution matrix", "",
             "Generated by `python scripts/generate_solution_matrix.py` from `scripts/traceability_data.py` (do not edit by hand). Customer needs are fictional assumptions "
             "([customer discovery](../customer-discovery/README.md)). **Status** is the catalogue status (verified, partially verified, implemented, not implemented), assessed by the "
             "implementing engineer; it is not independent validation. The authoritative requirement register is `docs/specification/v4.1-requirements.json` (238 requirements).", ""]
    counts = defaultdict(int)
    for r in t.REQUIREMENTS:
        counts[r["status"]] += 1
    lines += ["Catalogue status counts: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + f" (of {len(t.REQUIREMENTS)}).", ""]
    for part in sorted(by_part):
        lines += [f"## Specification part {part}", "", f"**Customer need.** {NEEDS.get(part, 'See the part text.')}", "",
                  "| Id | Requirement | Technical implementation (components and APIs) | Test cases | Acceptance criterion | Evidence | Status and limitation |", "|---|---|---|---|---|---|---|"]
        for r in by_part[part]:
            limit = f"**{r['status']}**" + (f": {r['limitation']}" if r["limitation"] else "")
            lines.append(f"| {r['id']} | {r['title']} | {cell(r['implementation'])} | {cell(r['tests'])} | {r['acceptance']} | {cell(r['evidence'])} | {limit} |")
        lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(t.REQUIREMENTS)} requirements)")


if __name__ == "__main__":
    main()
