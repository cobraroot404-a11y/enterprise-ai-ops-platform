"""Generate the requirements traceability matrix from scripts/traceability_data.py and validate it.

    python scripts/generate_traceability.py           # write docs/traceability/*.md|json
    python scripts/generate_traceability.py --check   # validate only (exit 1 on any problem)

Validation: every referenced implementation/test/evidence path exists; every `file::test_name` reference names a function that
exists in that file; a requirement is only 'verified' if it lists at least one test and one evidence artifact.
"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).parent))
from traceability_data import REQUIREMENTS  # noqa: E402

OUT = ROOT / "docs" / "traceability"
STATUSES = ("verified", "partially verified", "implemented", "not implemented")


def problems() -> list[str]:
    bad: list[str] = []
    seen: set[str] = set()
    for r in REQUIREMENTS:
        rid = r["id"]
        if rid in seen:
            bad.append(f"{rid}: duplicate id")
        seen.add(rid)
        if r["status"] not in STATUSES:
            bad.append(f"{rid}: unknown status {r['status']!r}")
        if r["status"] == "verified" and not (r["tests"] and r["evidence"]):
            bad.append(f"{rid}: marked verified without a test and an evidence artifact")
        if r["status"] in ("partially verified", "not implemented") and not r["limitation"]:
            bad.append(f"{rid}: {r['status']} requires a stated limitation")
        if r["status"] == "not implemented" and (r["tests"] or r["implementation"]):
            bad.append(f"{rid}: 'not implemented' must not list implementation or tests")
        for kind in ("implementation", "evidence"):
            for p in r[kind]:
                if not (ROOT / p).exists():
                    bad.append(f"{rid}: {kind} path missing: {p}")
        for t in r["tests"]:
            path, _, fn = t.partition("::")
            f = ROOT / path
            if not f.exists():
                bad.append(f"{rid}: test file missing: {path}")
            elif fn and not re.search(rf"\bdef {re.escape(fn)}\b", f.read_text(encoding="utf-8")):
                bad.append(f"{rid}: test function not found: {t}")
    return bad


def render() -> tuple[str, dict]:
    counts = Counter(r["status"] for r in REQUIREMENTS)
    lines = ["# Requirements traceability matrix (V4.1 specification)", "",
             "Generated by `python scripts/generate_traceability.py` from `scripts/traceability_data.py`; "
             "`tests/test_traceability.py` fails when a referenced file or test does not exist or when a requirement is "
             "marked *verified* without a test and an evidence artifact. Code existing is never treated as verification.", "",
             "Status vocabulary: **verified** (implemented, automated test, evidence artifact) - **partially verified** "
             "(verification incomplete, indirect or of part of the requirement) - **implemented** (code, no adequate test) - "
             "**not implemented** (planned phase noted).", "",
             "## Summary", "", "| Status | Count |", "|---|---|"]
    total = len(REQUIREMENTS)
    for s in STATUSES:
        lines.append(f"| {s} | {counts.get(s, 0)} |")
    lines += [f"| **total** | **{total}** |", "",
              "Requirement ids are `R<specification part>.<n>`; UAT, fault-injection and reliability reports cite the same ids.", "",
              "## Matrix", ""]
    for r in REQUIREMENTS:
        lines += [f"### {r['id']} - {r['title']}", "",
                  f"- **Specification part:** {r['part']} ({r['category']})",
                  f"- **Acceptance criterion:** {r['acceptance']}",
                  f"- **Implementation:** {', '.join(f'`{p}`' for p in r['implementation']) or '-'}",
                  f"- **Tests:** {', '.join(f'`{p}`' for p in r['tests']) or '-'}",
                  f"- **Evidence:** {', '.join(f'`{p}`' for p in r['evidence']) or '-'}",
                  f"- **Status:** {r['status']}",
                  f"- **Defect / limitation:** {r['limitation'] or 'none recorded'}", ""]
    data = {"counts": dict(counts), "total": total, "requirements": REQUIREMENTS}
    return "\n".join(lines), data


def main() -> int:
    bad = problems()
    if bad:
        print("\n".join(bad))
        return 1
    if "--check" in sys.argv:
        print(f"traceability OK: {len(REQUIREMENTS)} requirements")
        return 0
    md, data = render()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "requirements-traceability-matrix.md").write_text(md, encoding="utf-8", newline="\n")
    (OUT / "requirements-traceability-matrix.json").write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(REQUIREMENTS)} requirements; {data['counts']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
