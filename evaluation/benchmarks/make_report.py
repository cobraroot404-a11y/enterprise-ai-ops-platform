"""Render evaluation/reports/phase3/SUMMARY.md from the run folders' results.json (no numbers typed by hand).

Run: python evaluation/benchmarks/make_report.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REPORTS = ROOT / "evaluation" / "reports" / "phase3"


def load(p: Path):
    return json.loads((p / "results.json").read_text()), json.loads((p / "manifest.json").read_text())


def pct(n, d):
    return f"{n}/{d} ({100 * n / d:.1f}%)" if d else "n/a"


def row(label, values):
    return f"| {label} | " + " | ".join(str(v) for v in values) + " |"


def main():
    dirs = sorted(p for p in REPORTS.glob("2026*") if (p / "results.json").exists())
    real = [p for p in dirs if "ollama_sentence_transformers" in p.name]
    det = [p for p in dirs if "deterministic_deterministic" in p.name]
    out = ["# Phase 3 evaluation summary", "",
           "Generated by `python evaluation/benchmarks/make_report.py` from each run's `results.json`. "
           "Method, definitions and limits: `docs/evaluation/phase3-method.md`.", ""]
    first_m = load(real[-1])[1]
    hw, v, ds = first_m["hardware"], first_m["versions"], first_m["dataset"]
    out += ["## Environment (real-AI runs)", "",
            f"- Hardware: {hw['cpu']} ({hw['cpu_threads']} threads), {hw['ram_gb']} GB RAM, no GPU (CPU inference); {hw['os']}",
            f"- LLM: Ollama {v.get('ollama')} / `{v.get('ollama_model')}` digest `{v.get('ollama_model_digest')}`; options {v.get('ollama_options')}; prompt v{v.get('prompt_version')} (sha256 `{v.get('prompts_sha256', '')[:16]}...`)",
            f"- Embeddings: `{v['embedding_profile']}`; evidence threshold {v['embedding_evidence_threshold_used']} (chosen on dev split)",
            f"- Software: Python {v['python']}, torch {v.get('torch')}, transformers {v.get('transformers')}, sentence-transformers {v.get('sentence_transformers')}, PostgreSQL {v['postgres']}, pgvector {v['pgvector']}",
            f"- Dataset `{ds['name']}`: {ds['documents']} documents, {ds['chunks']} chunks; test split {ds['answerable_test']} answerable + {ds['unanswerable_test']} unanswerable queries; {ds['fault_reports']} fault reports; dataset hash `{ds['text_files_sha256'][:16]}...`",
            f"- Repetitions: {len(real)} complete real-AI runs; {ds['e2e_runs']} end-to-end workflow repetitions per run", ""]

    out += ["## Real AI runs (Ollama + MiniLM), held-out test split", "",
            "| Metric | " + " | ".join(p.name[:16] for p in real) + " |", "|---|" + "---|" * len(real)]
    rs = [load(p)[0] for p in real]

    def col(fn):
        return [fn(r) for r in rs]

    out += [
        row("Recall@5 (hybrid)", col(lambda r: f"{r['retrieval']['test']['recall_at_5']:.3f}")),
        row("Precision@5 (ceiling 0.2)", col(lambda r: f"{r['retrieval']['test']['precision_at_5']:.3f}")),
        row("MRR hybrid / vector-only / text-only", col(lambda r: f"{r['retrieval']['test']['mrr']:.3f} / {r['retrieval']['ablation_test']['vector']['mrr']:.3f} / {r['retrieval']['ablation_test']['fts']['mrr']:.3f}")),
        row("hit@1 hybrid / vector / text (of 36)", col(lambda r: f"{r['retrieval']['test']['hit_at_1']} / {r['retrieval']['ablation_test']['vector']['hit_at_1']} / {r['retrieval']['ablation_test']['fts']['hit_at_1']}")),
        row("Evidence gate passes answerable (of 36)", col(lambda r: r["retrieval"]["test"]["evidence_gate_pass_answerable"])),
        row("Evidence gate blocks unanswerable (of 8)", col(lambda r: r["retrieval"]["test"]["evidence_gate_blocks_unanswerable"])),
        row("Grounded verified answers", col(lambda r: pct(r["qa"]["grounded_answers"], r["qa"]["answerable_queries"]))),
        row("Citation correctness", col(lambda r: pct(round(r["qa"]["citation_correctness"] * r["qa"]["citations_emitted"]), r["qa"]["citations_emitted"]))),
        row("Withheld (unverifiable quote)", col(lambda r: r["qa"]["withheld_unverified_or_invalid"])),
        row("False abstentions (answerable)", col(lambda r: r["qa"]["false_abstentions"])),
        row("Correct abstentions (unanswerable, of 8)", col(lambda r: r["qa"]["correct_abstentions"])),
        row("Unanswerable answered (of 8)", col(lambda r: r["qa"]["wrongly_answered_unanswerable"])),
        row("Answers containing all key facts (proxy)", col(lambda r: pct(r["qa"]["answers_with_all_key_facts"], r["qa"]["answerable_queries"]))),
        row("Raw model output schema-valid (extraction, of 24)", col(lambda r: r["structured"]["model_output_schema_valid"])),
        row("Asset ID / category / priority correct (of valid)", col(lambda r: f"{r['structured']['asset_id_correct']} / {r['structured']['category_correct']} / {r['structured']['priority_correct']} of {r['structured']['model_output_schema_valid']}")),
        row("Pipeline outcome correct (created incident or expected rejection, of 24)", col(lambda r: r["structured"]["pipeline_ok_or_expected_rejection"])),
        row("End-to-end workflow completed, duplicates", col(lambda r: f"{r['e2e']['all_submitted']}, {r['e2e']['duplicates']}")),
        "",
        "### Latency (median / p95, seconds)", "",
        "| Measure | " + " | ".join(p.name[:16] for p in real) + " |", "|---|" + "---|" * len(real),
        row("Retrieval (embed query + hybrid SQL), n=44", col(lambda r: f"{r['retrieval']['latency_s']['median']} / {r['retrieval']['latency_s']['p95']}")),
        row("LLM inference per call, n~34", col(lambda r: f"{r['qa']['llm_inference_s']['median']} / {r['qa']['llm_inference_s']['p95']}")),
        row("Grounded-answer request (retrieval + LLM + verify), n=44", col(lambda r: f"{r['qa']['latency_wall_s']['median']} / {r['qa']['latency_wall_s']['p95']}")),
        row("Incident extraction request (2 LLM calls + retrieval), n=24", col(lambda r: f"{r['structured']['pipeline_latency_s']['median']} / {r['structured']['pipeline_latency_s']['p95']}")),
        row("End-to-end workflow (extract, draft, approve, submit), n=5", col(lambda r: f"{r['e2e']['total_s']['median']} / {r['e2e']['total_s']['p95']}")),
        row("Generation speed, tokens/s (median)", col(lambda r: r["qa"]["tokens_per_s"]["median"])),
        row("Model load (cold start, s) / embedder load (s)", col(lambda r: f"{r.get('llm_cold_start_s')} / {r['embedder_load_s']}")),
        "",
    ]
    valid_res = [r for r in rs if r["resources"].get("qa", {}).get("samples")]
    if valid_res:
        res = valid_res[-1]["resources"]
        out += ["### CPU and memory (last run with a working sampler; ~3 s samples)", "",
                "| Phase | samples | CPU mean % | CPU peak % | Ollama working set peak MB | Python working set peak MB | min free RAM MB (of " + str(res["qa"]["system_total_ram_mb"]) + ") |",
                "|---|---|---|---|---|---|---|"]
        for k in ("qa", "structured", "e2e"):
            x = res[k]
            out.append(f"| {k} | {x['samples']} | {x['cpu_pct_mean']} | {x['cpu_pct_peak']} | {x['ollama_working_set_mb_peak']} | {x['python_working_set_mb_peak']} | {x['system_free_ram_mb_min']} |")
        out.append("")
    if det:
        r = load(det[-1])[0]
        out += ["## Deterministic functional baseline (NOT AI performance)", "",
                "Test-only lexical embedder and extractive rule-based 'LLM'. Included only to show what the real backends are compared against; "
                "these numbers must not be quoted as AI results.", "",
                f"- Recall@5 {r['retrieval']['test']['recall_at_5']:.3f}, MRR {r['retrieval']['test']['mrr']:.3f}; grounded {r['qa']['grounded_answers']}/36; "
                f"citation correctness {r['qa']['citation_correctness']:.3f} over {r['qa']['citations_emitted']} citations; "
                f"unanswerable answered {r['qa']['wrongly_answered_unanswerable']}/8; key-fact answers {r['qa']['answers_with_all_key_facts']}/36", ""]
    out += ["## Targets from the V4.1 specification vs actual (real-AI runs)", "",
            "| Target | Actual | Met? |", "|---|---|---|",
            f"| Recall@5 at least 85% | {min(r['retrieval']['test']['recall_at_5'] for r in rs):.0%} on all {len(rs)} runs (corpus of {ds['chunks']} chunks saturates this metric) | yes, with that caveat |",
            f"| Citation correctness at least 95% | {min(r['qa']['citation_correctness'] for r in rs):.1%} to {max(r['qa']['citation_correctness'] for r in rs):.1%} | **no** |",
            f"| Structured ticket schema validity 100% | 100% of incidents that were created passed Pydantic validation (validated before storage); raw model output was schema-valid {min(r['structured']['model_output_schema_valid'] for r in rs)}/24 and the invalid one was a rejected hallucinated asset ID | schema gate yes; raw model output no |",
            "| Zero unauthorized submissions / duplicate tickets in tested retries | E2E runs: 0 duplicates; security and workflow suites in `evaluation/reports/phase3-gate/` | yes (as tested) |", ""]
    (REPORTS / "SUMMARY.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote", REPORTS / "SUMMARY.md")


if __name__ == "__main__":
    main()
